    def e(s, b, c): s.d.ellipse(b, fill=c)
    def r(s, b, c): s.d.rectangle(b, fill=c)
    def p(s, pts, c): s.d.polygon(pts, fill=c)
    def l(s, pts, c, w=1): s.d.line(pts, fill=c, width=w)
    def px(s, pts, c):
        for q in pts: s.d.point(q, fill=c)
    def se(s, b, c, hl=True):  # объёмный эллипс: тень снизу, блик сверху слева
        x0, y0, x1, y1 = b
        s.e(b, Dk(c, 45)); s.e((x0, y0, x1, y1 - max(1, (y1 - y0) // 6)), c)
        if hl: s.e((x0 + (x1 - x0) * .18, y0 + (y1 - y0) * .12, x0 + (x1 - x0) * .42, y0 + (y1 - y0) * .3), L(c, 55))
    def sr(s, b, c):
        x0, y0, x1, y1 = b; s.r(b, Dk(c, 40)); s.r((x0, y0, x1 - 2, y1), c); s.r((x0 + 1, y0 + 1, x0 + 2, y1 - 1), L(c, 50))
    def steam(s, x, y, n=3, c=(236, 238, 248)):
        for i in range(n):
            for j in range(10):
                if j % 5 != 4: s.post.append(((x + i * 6 + round(1.5 * math.sin(j * .8 + i)), y - j), c))
    def done(s, name):
        a = np.asarray(s.im).copy(); m = a[..., 3] > 0; pp = np.pad(m, 1)
        nb = pp[:-2, 1:-1] | pp[2:, 1:-1] | pp[1:-1, :-2] | pp[1:-1, 2:]
        a[nb & ~m] = INK + (255,)
        for (x, y), c in s.post:
            if 0 <= x < W and 0 <= y < H: a[int(y), int(x)] = c + (255,)
        fg = Image.fromarray(a, 'RGBA'); out = s.bg.copy(); out.alpha_composite(fg)
        # тень под предметами на столе
        out.save(f'dish-{name}.png'); return out
