W, H = 48, 40
INK = (26, 21, 40)
class P:
    def __init__(s):
        s.im = Image.new('RGBA', (W, H), (0, 0, 0, 0)); s.d = ImageDraw.Draw(s.im); s.post = []
    def e(s, b, c): s.d.ellipse(b, fill=c)
    def r(s, b, c): s.d.rectangle(b, fill=c)
    def p(s, pts, c): s.d.polygon(pts, fill=c)
    def l(s, pts, c, w=1): s.d.line(pts, fill=c, width=w)
    def px(s, pts, c):
        for q in pts: s.d.point(q, fill=c)
    def done(s, name):
        a = np.asarray(s.im).copy(); m = a[..., 3] > 0; pp = np.pad(m, 1)
        nb = pp[:-2, 1:-1] | pp[2:, 1:-1] | pp[1:-1, :-2] | pp[1:-1, 2:]
        a[nb & ~m] = INK + (255,)
        for (x, y), c in s.post:
            if 0 <= x < W and 0 <= y < H: a[y, x] = c + (255,)
        Image.fromarray(a, 'RGBA').save(f'dish-{name}.png'); return Image.fromarray(a, 'RGBA')
def lighter(c, k=40): return tuple(min(255, v + k) for v in c[:3])
def darker(c, k=40): return tuple(max(0, v - k) for v in c[:3])
