    prof = [(3, 0), (5, 6), (8, 9), (12, 10), (20, 10), (28, 9), (36, 9), (42, 10), (48, 12), (56, 16), (64, 19), (72, 20), (78, 19), (84, 15), (88, 9), (90, 3)]
