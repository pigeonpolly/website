def ink_outline(im):
    a = np.asarray(im).copy(); m = a[..., 3] > 0; pp = np.pad(m, 1)
    nb = pp[:-2, 1:-1] | pp[2:, 1:-1] | pp[1:-1, :-2] | pp[1:-1, 2:]; a[nb & ~m] = INK + (255,)
    return Image.fromarray(a, 'RGBA')


