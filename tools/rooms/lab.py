def L(c, k=30): return tuple(min(255, v + k) for v in c[:3])
def D(c, k=30): return tuple(max(0, v - k) for v in c[:3])
def mix(a, b, t): return tuple(int(a[i] + (b[i] - a[i]) * t) for i in range(3))
def R(b, c): d.rectangle(b, fill=c)
def E(b, c): d.ellipse(b, fill=c)
def P(pts, c): d.polygon(pts, fill=c)
def Ln(pts, c, w=1): d.line(pts, fill=c, width=w)
def px(x, y, c): d.point((x, y), fill=c)
def box(b, c, k=26):
    x0, y0, x1, y1 = b; R(b, c); R((x0, y0, x1, y0), L(c, k)); R((x0, y0, x0, y1), L(c, k // 2)); R((x1, y0, x1, y1), D(c, k)); R((x0, y1, x1, y1), D(c, k))
def grad(b, c0, c1):
    x0, y0, x1, y1 = b
    for y in range(y0, y1 + 1): R((x0, y, x1, y), mix(c0, c1, (y - y0) / max(1, y1 - y0)))
def speckle(b, cols, n):
    x0, y0, x1, y1 = b
    for _ in range(n): px(rnd.randint(x0, x1), rnd.randint(y0, y1), rnd.choice(cols))


