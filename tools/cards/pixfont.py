# латиница — теми же начертаниями, где буквы совпадают по форме
_LAT = {'A': 'А', 'B': 'В', 'C': 'С', 'E': 'Е', 'H': 'Н', 'K': 'К', 'M': 'М',
        'O': 'О', 'P': 'Р', 'T': 'Т', 'X': 'Х'}

# диакритика (латышский): знак рисуется вне клетки 5x7 — над или под буквой
_MAC = [(1, -2), (2, -2), (3, -2)]
_CARON = [(1, -2), (3, -2), (2, -1)]
_CED = [(2, 7), (1, 8)]
MARKS = {
    'Ā': ('А', _MAC), 'Ē': ('Е', _MAC), 'Ī': ('I', _MAC), 'Ū': ('U', _MAC),
    'Č': ('С', _CARON), 'Š': ('S', _CARON), 'Ž': ('Z', _CARON),
    'Ģ': ('G', _CED), 'Ķ': ('К', _CED), 'Ļ': ('L', _CED), 'Ņ': ('N', _CED),
}

CHAR_W, CHAR_H, TRACK = 5, 7, 1


def glyph(ch):
    ch = ch.upper()
    if ch in F5:
        return F5[ch]
    if ch in MARKS:
        return F5[MARKS[ch][0]]
    if ch in _LAT:
        return F5[_LAT[ch]]
    return F5['?']


def width(s, scale=1, track=TRACK):
    return (len(s) * (CHAR_W + track) - track) * scale


def text(d, x, y, s, col, scale=1, track=TRACK):
    """Рисует строку; (x,y) — левый верхний угол. Возвращает ширину."""
    cx = x
    for ch in s:
        up = ch.upper()
        g = glyph(up)
        for j, row in enumerate(g):
            for i, c in enumerate(row):
                if c == '#':
                    if scale == 1:
                        d.point((cx + i, y + j), fill=col)
                    else:
                        d.rectangle((cx + i * scale, y + j * scale,
                                     cx + i * scale + scale - 1, y + j * scale + scale - 1), fill=col)
        if up in MARKS:
            for dx, dy in MARKS[up][1]:
                if scale == 1:
                    d.point((cx + dx, y + dy), fill=col)
                else:
                    d.rectangle((cx + dx * scale, y + dy * scale,
                                 cx + dx * scale + scale - 1, y + dy * scale + scale - 1), fill=col)
        cx += (CHAR_W + track) * scale
    return cx - x - track * scale


def ctext(d, x, y, s, col, scale=1, track=TRACK):
    """Строка по центру x."""
    return text(d, x - width(s, scale, track) / 2, y, s, col, scale, track)


def shadow_text(d, x, y, s, col, shadow, scale=1, track=TRACK, dx=1, dy=1):
    text(d, x + dx, y + dy, s, shadow, scale, track)
    text(d, x, y, s, col, scale, track)
